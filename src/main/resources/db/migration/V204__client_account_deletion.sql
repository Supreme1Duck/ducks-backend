-- Удаление аккаунта клиента. Необратимое: восстановить аккаунт нельзя, повторный вход по
-- тому же номеру создаёт новый.
-- 1. deletion_requested_at — заявка. Доступ по токену закрывается сразу, номер тут же
--    освобождается (phone_number под уникальным индексом, иначе повторная регистрация
--    упёрлась бы в него), а сам номер переезжает в deleted_phone_number: продавцу он ещё
--    нужен, чтобы опознать клиента по заказу последних дней.
-- 2. deleted_at — строка обезличена окончательно: стёрты имя, фамилия, fcm-токен и
--    отложенный номер.
-- Саму строку не удаляем: на неё ссылаются заказы, из которых считается выручка кофеен.

ALTER TABLE public.ducks_user_table
    ADD COLUMN deletion_requested_at bigint,
    ADD COLUMN deleted_at            bigint,
    ADD COLUMN deleted_phone_number  text;
